def split_dataset():
  #resize to 224 × 224 for standard input
  transform = transforms.Compose([
      transforms.Resize((224, 224)),
      transforms.ToTensor(),
      transforms.Normalize(mean=[0.485, 0.456, 0.406],
                          std=[0.229, 0.224, 0.225])
  ])

  #retrive full dataset
  train_ds_full = datasets.OxfordIIITPet("./data", split="trainval", target_types="category",
                                          transform=transform, download=True)
  eval_ds_full = datasets.OxfordIIITPet("./data", split="trainval", target_types="category",
                                          transform=transform, download=True)
  test_ds = datasets.OxfordIIITPet("./data", split="test", target_types="category",
                                          transform=transform, download=True)
  # one breed label per image
  labels = train_ds_full._labels

  # Stratified split by breed, each breed keep the same rateo on the two split
  train_idx, val_idx = train_test_split(
      range(len(labels)),
      test_size=0.2,
      stratify=labels,
      random_state=42,
  )

  # 80/20 ds_full splitted
  ds_train = Subset(train_ds_full, train_idx)
  ds_eval = Subset(eval_ds_full, val_idx)

  return ds_train, ds_eval, test_ds

#train and validation
def epochTrain(model, train_loader, criterion, optimizer):
  model.train()
  n = 0
  tot_loss = 0.0
  tot_acc = 0.0

  for images, labels in train_loader:
    images, labels = images.to(device), labels.to(device)

    optimizer.zero_grad()
    outputs = model(images)
    loss = criterion(outputs, labels)
    loss.backward()
    optimizer.step()
    preds = (outputs.argmax(dim=1) == labels).sum().item()

    tot_loss += loss.item() * images.size(0)
    tot_acc += preds
    n += images.size(0)

  return tot_acc / n, tot_loss / n

def epochVal(model, val_loader, criterion):
  with torch.no_grad():
    model.eval()
    n = 0
    tot_loss = 0.0
    tot_acc = 0.0

    for images, labels in val_loader:
      images, labels = images.to(device), labels.to(device)

      outputs = model(images)
      loss = criterion(outputs, labels)

      preds = (outputs.argmax(dim=1) == labels).sum().item()


      tot_loss += loss.item() * images.size(0)
      tot_acc += preds
      n += images.size(0)

  return tot_acc / n, tot_loss / n

#training on all the epochs
def running_epoch(model, train_loader, eval_loader, criterion, optimizer):

  f_best_acc = 0
  p_best_acc = 0
  epochs = 12

  f_epoch_pass = 0
  for epoch in range(epochs):
    f_t_acc, f_t_loss = epochTrain(model, train_loader, criterion, optimizer)
    f_v_acc, f_v_loss = epochVal(model, eval_loader, criterion)

    f_epoch_pass += 1
    if(f_epoch_pass == epochs/4):
      print(f"other {epochs/4} epochs achieved!")
      print(f"train loss {f_t_loss:.3f} train acc {f_t_acc:.3f}\nval loss {f_v_loss:.3f} val acc {f_v_acc:.3f}\n\n\n")
      f_epoch_pass = 0

    if f_v_acc > f_best_acc:
            best_epoch, f_best_acc, f_best_state = epoch, f_v_acc, copy.deepcopy(model.state_dict())

  return best_epoch, f_best_state

#function to plot confusion matrix
def plotCm(cm,test_ds):
  class_names = test_ds.classes
  cm_norm = cm / cm.sum(axis=1, keepdims=True)   # each row sums to 1 (per-breed recall)

  fig, ax = plt.subplots(figsize=(14, 12))
  im = ax.imshow(cm_norm, cmap="Blues")
  ax.set_xticks(range(37)); ax.set_yticks(range(37))
  #ax.set_xticklabels(class_names, rotation=90, fontsize=7)
  #ax.set_yticklabels(class_names, fontsize=7)
  ax.set_xlabel("Predicted breed"); ax.set_ylabel("True breed")
  ax.set_title("Confusion matrix (normalized by true class)")
  fig.colorbar(im)
  plt.tight_layout()
  plt.show()

def show_val(acc, cm, macro_f1):
    print(f"Test Set Accuracy: {acc:.2f}%")
    print(f"Test Set Macro F1 score: {macro_f1:.2f}")
    plotCm(cm, test_ds)

#final test

def test_model(model, test_loader):
  model.eval()
  correct = 0
  tot = 0

  with torch.no_grad():
    all_preds, all_labels = [], []
    for images, labels in test_loader:
      images, labels = images.to(device), labels.to(device)
      outputs = model(images)

      #total accuracy
      _, pred = torch.max(outputs, 1)
      tot += labels.size(0)
      correct += (pred == labels).sum().item()

      #f1-score
      all_preds.append(outputs.argmax(dim=1).cpu())
      all_labels.append(labels.cpu())


    acc = 100.0 * correct/tot
    x_true = torch.cat(all_labels).numpy()
    y_pred = torch.cat(all_preds).numpy()
    macro_f1 = f1_score(x_true, y_pred, average="macro")
    #print(classification_report(x_true, y_pred, target_names=test_ds.classes))
    cm = confusion_matrix(x_true, y_pred, labels=range(37))

    show_val(acc, cm, macro_f1)

#TRAIN&TEST OF THE ENTIRE NETWORK
def train_test_net(model_ft, train_loader, eval_loader, test_loader, criterion, optimizer):
  print("TRAIN OF THE FULL NETWORK")
  f_epoch, f_best_state = running_epoch(model_ft, train_loader, eval_loader, criterion, optimizer)

  model_ft.load_state_dict(f_best_state)           # restore best epoch


  print("TEST OF THE FULL FINE TUNING")
  test_model(model_ft,test_loader)

#TRAIN&TEST ONLY OF THE FULLY CONNECTED LAYERS
def train_test_oc(model_oc, train_loader, eval_loader, test_loader, criterion):
  #freeze all
  for param in model_oc.parameters():
      param.requires_grad = False

  #unfreeze the fully connected layer
  for param in model_oc.classifier[3].parameters(): #only the last layer to reduce overfitting
      param.requires_grad = True

  optimizer = torch.optim.Adam(filter(lambda p: p.requires_grad, model_oc.parameters()), lr=1e-4) #1e-3 overfit

  print("TRAIN OF ONLY THE FULLY CONNECTED LAYERS")
  c_epoch, c_best_state = running_epoch(model_oc, train_loader, eval_loader, criterion, optimizer)

  model_oc.load_state_dict(c_best_state)

  print("\n\n\nTEST OF THE ONLY CONVOLUTIONAL LAYER TRAINING")
  test_model(model_oc,test_loader)

def extract(dataset, prenet):
    loader = DataLoader(dataset, batch_size=64, shuffle=False)
    x, y = [], []
    for images, labels in loader:
        x.append(prenet(images.to(device)).cpu())
        y.append(labels)
    return torch.cat(x).numpy(), torch.cat(y).numpy()

def feat_extr_tc(prenet, ds_train, ds_val, ds_test):
  prenet = prenet.to(device).eval()
  for p in prenet.parameters():
      p.requires_grad = False

  with torch.no_grad():
    x_train, y_train = extract(ds_train, prenet)
    x_val,   y_val   = extract(ds_val, prenet)
    x_test,  y_test  = extract(ds_test, prenet)

    configs = [(n, d) for n in [100, 300, 500] for d in [None, 20]] #random forest hyperparam
    best_acc, best_cfg, best_rf = -1, None, None

    for n, d in configs:
      rf = RandomForestClassifier(n_estimators=n, max_depth=d, random_state=0, n_jobs=-1)
      rf.fit(x_train, y_train)
      acc = accuracy_score(y_val, rf.predict(x_val))
      if acc > best_acc:
          best_acc, best_cfg, best_rf = acc, (n, d), rf


  pred = best_rf.predict(x_test)
  print(f"test acc {accuracy_score(y_test, pred):.4f} | macro F1 {f1_score(y_test, pred, average='macro'):.4f}")

  cm = confusion_matrix(y_test, pred, labels=range(37))
  plotCm(cm, ds_test)

